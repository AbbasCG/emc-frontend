/** يولّد ملف القالب في المتصفح: ورقة بيانات بأمثلة لكل الأنواع + ورقة إرشادات. */
export function downloadCatalogTemplate(): void {
  const wb = XLSX.utils.book_new()

  const dataSheet = XLSX.utils.json_to_sheet(EXAMPLE_ROWS, { header: [...TEMPLATE_COLUMNS] })
  dataSheet['!cols'] = TEMPLATE_COLUMNS.map((c) => ({ wch: Math.max(16, c.length + 4) }))
  XLSX.utils.book_append_sheet(wb, dataSheet, 'المنتجات')

  const guideSheet = XLSX.utils.aoa_to_sheet(GUIDE_ROWS)
  guideSheet['!cols'] = [{ wch: 34 }, { wch: 10 }, { wch: 90 }]
  XLSX.utils.book_append_sheet(wb, guideSheet, 'الإرشادات')

  XLSX.writeFile(wb, 'EMC-catalog-template.xlsx')
}

/** يقرأ ملف المستخدم ويعيد صفوف الورقة الأولى ككائنات بمفاتيح الأعمدة. */
export async function parseCatalogFile(file: File): Promise<TemplateRow[]> {
  const buffer = await file.arrayBuffer()
  const wb = XLSX.read(buffer, { type: 'array' })
  const sheet = wb.Sheets[wb.SheetNames[0]]
  return XLSX.utils.sheet_to_json<TemplateRow>(sheet, { defval: '' })
}
